/// How a concept group is looked up: every term, split into words, points back
/// at the groups it belongs to.
///
/// Built once at startup. A term like "worn out" contributes its two words, so
/// a note containing "worn out" scores as strongly as one containing "tired".
///
/// Stopwords and one-letter words are dropped here, not at match time: phrases
/// like "went for a walk" and "to do" contain filler, and indexing "for" or "a"
/// would make those concepts match almost every sentence.
final Map<String, Set<int>> _termIndex = _buildIndex();

Map<String, Set<int>> _buildIndex() {
  final index = <String, Set<int>>{};
  for (var i = 0; i < concepts.length; i++) {
    for (final term in concepts[i].terms) {
      for (final word in term.split(RegExp(r'\s+'))) {
        if (word.length < 3) continue;
        if (_fillerWords.contains(word)) continue;
        index.putIfAbsent(word, () => <int>{}).add(i);
      }
    }
  }
  return index;
}

