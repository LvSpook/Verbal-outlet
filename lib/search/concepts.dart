/// Concept group ids whose vocabulary includes [word].
Set<int> conceptsFor(String word) => _termIndex[word] ?? const <int>{};

/// Concept group id -> the words that actually pulled the match in, so the UI
/// can say "also matched 'exhausted'".
Map<int, Set<String>> conceptHitsFor(Iterable<String> words) {
  final hits = <int, Set<String>>{};
  for (final word in words) {
    for (final id in conceptsFor(word)) {
      hits.putIfAbsent(id, () => <String>{}).add(word);
    }
  }
  return hits;
}

/// All the words in a concept group, for expanding a query.
///
/// Filler is filtered out here too, so a query never expands into words that
/// appear in every sentence.
Set<String> conceptVocabulary(int id) {
  final words = <String>{};
  for (final term in concepts[id].terms) {
    for (final word in term.split(RegExp(r'\s+'))) {
      if (word.length < 3) continue;
      if (_fillerWords.contains(word)) continue;
      words.add(word);
    }
  }
  return words;
}
