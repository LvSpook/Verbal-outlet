/// Concept groups that let a search find related wording, not just the same
/// letters.
///
/// Each group is a bag of words and phrases that all mean roughly the same
/// thing in everyday note-taking. Searching any member also matches the others,
/// so "tired" finds "exhausted", "walk" finds "stroll", and "money" finds
/// "rent" and "bills".
///
/// Groups are intentionally small and concrete. A sprawling thesaurus produces
/// false hits ("great" matching "terrible" through some shared ancestor), which
/// is worse than missing a synonym in a personal diary.
///
/// Anything added here should be a word a person would actually write in a
/// note. Multi-word entries are matched as phrases, and their weight is spread
/// across the words so they do not outrank a direct hit.
library;

/// A named cluster of interchangeable or closely related words.
class Concept {
  const Concept(this.name, this.terms);

  /// Human-readable label, used in the "why this matched" explanation.
  final String name;

  /// Words and short phrases, lower case. Multi-word entries are allowed.
  final List<String> terms;
}

